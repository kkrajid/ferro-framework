"""Renders migration files as readable Python."""

from __future__ import annotations

import datetime as dt
import json
import uuid
from collections.abc import Sequence
from decimal import Decimal
from typing import Any

from ferro.migrations.errors import MigrationError
from ferro.migrations.ops import Operation

__all__ = ["render_migration", "render_value"]


def render_value(value: Any, imports: set[str]) -> str:
    """Python source for a default value written into a migration."""
    if value is None or isinstance(value, bool | int | float):
        return repr(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, Decimal):
        imports.add("from decimal import Decimal")
        return f'Decimal("{value}")'
    if isinstance(value, uuid.UUID):
        imports.add("from uuid import UUID")
        return f'UUID("{value}")'
    if isinstance(value, dt.date | dt.time):
        imports.add("import datetime")
        return repr(value)
    if isinstance(value, list | tuple):
        return "[" + ", ".join(render_value(v, imports) for v in value) + "]"
    if isinstance(value, dict):
        items = (
            f"{render_value(k, imports)}: {render_value(v, imports)}" for k, v in value.items()
        )
        return "{" + ", ".join(items) + "}"
    raise MigrationError(f"cannot write the value {value!r} into a migration file")


def render_migration(
    dependencies: Sequence[str], operations: Sequence[Operation], version: str
) -> str:
    imports: set[str] = set()
    body = "".join(f"        {operation.render(8, imports)},\n" for operation in operations)
    operations_block = f"    operations=[\n{body}    ],\n" if operations else "    operations=[],\n"
    dependencies_text = "[" + ", ".join(json.dumps(d) for d in dependencies) + "]"
    stamp = dt.datetime.now(dt.UTC).strftime("%Y-%m-%d %H:%M UTC")
    header = f'"""Generated by Ferro {version} on {stamp}."""\n\n'
    stdlib = "".join(f"{line}\n" for line in sorted(imports))
    return (
        header
        + (stdlib + "\n" if stdlib else "")
        + "from ferro.migrations import Migration, ops\n\n"
        + "migration = Migration(\n"
        + f"    dependencies={dependencies_text},\n"
        + operations_block
        + ")\n"
    )
